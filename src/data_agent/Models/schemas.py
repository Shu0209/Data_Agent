
from typing import Annotated, Literal
from langchain_core.messages import AnyMessage
from langgraph.graph.message import add_messages

from pydantic import BaseModel, Field


class AgentSchema(BaseModel):
    messages: Annotated[list[AnyMessage], add_messages] = Field(
        default_factory=list,
        description="Messages History"
    )

    user_input:str=Field(...,description="The original question asked by the user")

    curated_ques: str = Field(
        default="",
        description="Curated user question"
    )

    prompt_query_context: str = Field(
        default="",
        description="Detailed prompt containing SQL database context"
    )

    is_safe: Literal["Yes", "No"] = Field(
        default="No",
        description="Whether the generated SQL query is safe to execute"
    )

    comments : str = Field(default="", description="Comments regarding the safety of the generated SQL query")

    generated_sql_query: str = Field(
        default="",
        description="SQL query generated by the agent"
    )

    sql_query_execution_result: str = Field(
        default="",
        description="Result of executing the generated SQL query"
    )

    final_answer: str = Field(
        default="",
        description="Final answer generated by the agent based on the SQL query"
    )


class JudgeSchema(BaseModel):
    answer:Literal["Yes","No"] = Field(...,description="Indicates whether the generated SQL query is safe to execute or not")

    comments: str=Field(...,description="Additional comments or feedback for the judge model regarding the SQL query")